"""Generate GrafanaDashboard resources (Grafana Operator) for multi-cluster Grafana setups.

Sample code, provided as is under the MIT License. Not an AtScale product. See DISCLAIMER.md.

Purpose: wraps the dashboards in GrafanaDashboard resources (grafana.integreatly.org/v1beta1) for sites that
deploy dashboards with the Grafana Operator and GitOps (Flux, Argo CD), and makes them multi-cluster: a
multi-select "cluster" variable on top, and cluster=~"$cluster" in every PromQL selector, so the same
dashboard works on a central Grafana that reads the metrics of several Kubernetes clusters.
Inputs: generate.py, generate_elastic.py. Outputs: deploy/grafana-operator/*.yaml and kustomization.yaml.
Run: python3 dashboard/generate_grafana_operator.py
"""
import copy
import json
import re
from pathlib import Path

import generate as g
import generate_elastic as ge

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "deploy" / "grafana-operator"
CLUSTER_LABEL = "cluster"
CLUSTER_METRIC = "atscale_query_duration_seconds_count"
# metric selector with braces, and a bare metric name (only in label_values() variable queries)
WITH_BRACES = re.compile(r"\b(atscale_[a-z_]+)\{")
BARE = re.compile(r"\b(atscale_[a-z_]+)\b(?![{\w])")


def add_cluster(promql):
    promql = WITH_BRACES.sub(r'\1{%s=~"$%s",' % (CLUSTER_LABEL, CLUSTER_LABEL), promql)
    return BARE.sub(r'\1{%s=~"$%s"}' % (CLUSTER_LABEL, CLUSTER_LABEL), promql)


def cluster_variable():
    q = "label_values(%s, %s)" % (CLUSTER_METRIC, CLUSTER_LABEL)
    return {"name": CLUSTER_LABEL, "label": "Cluster", "type": "query", "datasource": g.DS,
            "query": {"query": q, "refId": "StandardVariableQuery"}, "definition": q,
            "refresh": 2, "multi": True, "includeAll": True, "sort": 1,
            "current": {"selected": True, "text": ["All"], "value": ["$__all"]}}


def multicluster(dash):
    dash = copy.deepcopy(dash)
    for p in dash["panels"]:
        for t in p.get("targets", []):
            if t.get("datasource", {}).get("type") == "prometheus" and "expr" in t:
                t["expr"] = add_cluster(t["expr"])
    tl = []
    for v in dash["templating"]["list"]:
        if v.get("type") == "query" and v.get("datasource", {}).get("type") == "prometheus":
            v["definition"] = add_cluster(v["definition"])
            v["query"]["query"] = add_cluster(v["query"]["query"])
        tl.append(v)
        if v["name"] == "datasource":
            tl.append(cluster_variable())
    dash["templating"]["list"] = tl
    return dash


def resource(name, dash):
    """GrafanaDashboard as YAML text; json is a literal block so the file stays readable."""
    body = json.dumps(dash, indent=2)
    return "\n".join([
        "# Generated by dashboard/generate_grafana_operator.py, do not edit by hand.",
        "# Set instanceSelector to the labels of your Grafana instance and folder to your Grafana folder.",
        "apiVersion: grafana.integreatly.org/v1beta1",
        "kind: GrafanaDashboard",
        "metadata:",
        "  name: %s" % name,
        "  annotations:",
        "    # Flux must not substitute the ${...} Grafana variables in the dashboard JSON",
        "    kustomize.toolkit.fluxcd.io/substitute: disabled",
        "spec:",
        "  allowCrossNamespaceImport: true",
        "  instanceSelector:",
        "    matchLabels:",
        "      dashboards: grafana",
        "  folder: AtScale",
        "  json: |",
        "\n".join("    " + line for line in body.splitlines()),
        ""])


DASHBOARDS = {
    "atscale-query-lifecycle": g.dash,
    "atscale-query-lifecycle-es": ge.build(),
}

if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    files = []
    for name, dash in DASHBOARDS.items():
        path = OUT / (name + ".yaml")
        path.write_text(resource(name, multicluster(dash)))
        files.append(path.name)
        print("wrote", path.relative_to(ROOT))
    (OUT / "kustomization.yaml").write_text(
        "# Pick the dashboards you need: atscale-query-lifecycle (logs in Loki) or atscale-query-lifecycle-es\n"
        "# (logs in Elasticsearch). Set the namespace to your tenant namespace.\n"
        "apiVersion: kustomize.config.k8s.io/v1beta1\nkind: Kustomization\nresources:\n"
        + "".join("  - %s\n" % f for f in files))
    print("wrote", (OUT / "kustomization.yaml").relative_to(ROOT))
